import json
from pathlib import Path

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import FileResponse, PlainTextResponse

from app.models import ResponseVerificationRequest, VerificationReport
from app.verifier import verify_response

app = FastAPI(
    title="EvidenceCheck",
    description="Automated fact-checking, citation hygiene, and claim entailment verification engine.",
    version="0.1.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

WEB_DIR = Path(__file__).parent / "web"
BENCHMARK_PATH = Path(__file__).parents[1] / "benchmarks" / "claims_with_sources.json"


@app.get("/health", include_in_schema=False)
def health():
    return {"status": "ok", "service": "evidencecheck"}


@app.get("/api/benchmark-dataset")
def get_benchmark_dataset():
    if not BENCHMARK_PATH.exists():
        return {"cases": []}
    return json.loads(BENCHMARK_PATH.read_text(encoding="utf-8"))


@app.post("/api/verify", response_model=VerificationReport)
def verify(request: ResponseVerificationRequest):
    return verify_response(request)


@app.post("/api/reports/markdown")
def generate_markdown(request: ResponseVerificationRequest):
    report = verify_response(request)

    claim_rows = []
    for c in report.claims:
        cited = f"`{c.cited_doc_id}`" if c.cited_doc_id else "None"
        claim_rows.append(
            f"| `{c.claim_id}` | {c.claim_text} | {cited} | **{c.status.value}** | {c.reasoning} |"
        )
    rows_text = (
        "\n".join(claim_rows) if claim_rows else "| None | - | - | - | No claims parsed |"
    )

    md = f"""# EvidenceCheck - Claim Grounding & Citation Audit

**Original Query:** {request.query or "General Chatbot Answer Verification"}  
**Total Claims Extracted:** {report.total_claims}  
**Grounding Ratio:** `{round(report.grounding_ratio * 100, 1)}%`  
**Citation Precision:** `{round(report.citation_precision * 100, 1)}%`  
**Hallucination Risk Tier:** `{report.hallucination_risk.value}`  

---

## 1. Metric Breakdown
- **Supported Claims:** `{report.supported_claims}/{report.total_claims}`
- **Contradicted Claims:** `{report.contradicted_claims}/{report.total_claims}`
- **Unverified Claims:** `{report.unverified_claims}/{report.total_claims}`

---

## 2. Claim-by-Claim Entailment Verification
| Claim ID | Extracted Statement | Cited Source | Status | Entailment Reasoning |
|---|---|---|---|---|
{rows_text}

_Generated by EvidenceCheck Citation & Grounding Engine v0.1.0_
"""
    return PlainTextResponse(md, media_type="text/markdown")


@app.get("/", include_in_schema=False)
def index():
    return FileResponse(WEB_DIR / "index.html")


@app.get("/app.js", include_in_schema=False)
def javascript():
    return FileResponse(WEB_DIR / "app.js", media_type="text/javascript")


@app.get("/style.css", include_in_schema=False)
def stylesheet():
    return FileResponse(WEB_DIR / "style.css", media_type="text/css")
